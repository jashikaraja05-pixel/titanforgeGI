export function getAvailableCountries(): { code: string; name: string }[] {
  return Object.values(REGIONS_AND_DISTRICTS).map((c) => ({
    code: c.countryCode,
    name: c.countryName,
  }));
}

export function getStatesForCountry(countryCode: string = 'IN'): string[] {
  const data = REGIONS_AND_DISTRICTS[countryCode] || REGIONS_AND_DISTRICTS.IN;
  return Object.keys(data.states);
}

export function getDistrictsForState(stateName: string, countryCode: string = 'IN'): string[] {
  const data = REGIONS_AND_DISTRICTS[countryCode] || REGIONS_AND_DISTRICTS.IN;
  return data.states[stateName] || [];
}
